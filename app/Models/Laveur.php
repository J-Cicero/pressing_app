<?php

namespace App\Models;

use Carbon\Carbon;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

class Laveur extends Model
{
    use HasFactory;

    /**
     * The attributes that are mass assignable.
     *
     * @var list<string>
     */
    protected $fillable = [
        'pressing_id',
        'nom',
        'telephone',
        'type_remuneration',
        'valeur_remuneration',
        'actif',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'valeur_remuneration' => 'decimal:2',
            'actif' => 'boolean',
        ];
    }

    /**
     * Get the establishment that employs this washer.
     *
     * @return BelongsTo<Pressing, $this>
     */
    public function pressing(): BelongsTo
    {
        return $this->belongsTo(Pressing::class);
    }

    /**
     * Get the invoices/tickets processed by this washer.
     *
     * @return HasMany<Facture, $this>
     */
    public function factures(): HasMany
    {
        return $this->hasMany(Facture::class);
    }

    /**
     * Compute commission for a given invoice (strictly 30% of prestation amount).
     */
    public function calculerCommission(Facture $facture): float
    {
        // Règle d'entreprise stricte : 30% du montant total des prestations accomplies
        $taux = ($this->type_remuneration === 'pourcentage' && (float) $this->valeur_remuneration > 0)
            ? ((float) $this->valeur_remuneration / 100)
            : 0.30;

        return round((float) $facture->montant_total * $taux, 2);
    }

    /**
     * Calculate total commissions earned on a given date.
     */
    public function commissionsDate(Carbon|string $date): float
    {
        $factures = $this->factures()
            ->whereDate('created_at', $date)
            ->get();

        return $factures->sum(fn (Facture $f) => $this->calculerCommission($f));
    }

    /**
     * Get invoices processed by this washer during a specific month (format: YYYY-MM).
     *
     * @return HasMany<Facture, $this>
     */
    public function facturesMois(string $anneeMois): HasMany
    {
        $parts = explode('-', $anneeMois);
        $year = (int) ($parts[0] ?? date('Y'));
        $month = (int) ($parts[1] ?? date('m'));

        return $this->factures()
            ->whereYear('created_at', $year)
            ->whereMonth('created_at', $month);
    }

    /**
     * Total washes completed by this washer in a given month.
     */
    public function nombreLavagesMois(string $anneeMois): int
    {
        return $this->facturesMois($anneeMois)->count();
    }

    /**
     * Total revenue generated by this washer in a given month.
     */
    public function totalCaMois(string $anneeMois): float
    {
        return (float) $this->facturesMois($anneeMois)->sum('montant_total');
    }

    /**
     * Total salary/commission payout due to this washer for a given month.
     */
    public function totalCommissionMois(string $anneeMois): float
    {
        $factures = $this->facturesMois($anneeMois)->get();

        return (float) $factures->sum(fn (Facture $f) => $this->calculerCommission($f));
    }

    /**
     * Get the monthly payments recorded for this washer.
     *
     * @return HasMany<PaiementLaveur, $this>
     */
    public function paiements(): HasMany
    {
        return $this->hasMany(PaiementLaveur::class);
    }

    /**
     * Get payment settlement record for a specific month.
     */
    public function paiementMois(string $anneeMois): ?PaiementLaveur
    {
        return $this->paiements()->where('mois', $anneeMois)->first();
    }

    /**
     * Check if the washer's salary for a given month has been paid physically.
     */
    public function estPayeMois(string $anneeMois): bool
    {
        $paiement = $this->paiementMois($anneeMois);

        return $paiement !== null && $paiement->statut === 'paye';
    }

    /**
     * Calculate the remaining balance to pay for a given month (0 if settled).
     */
    public function resteAPayerMois(string $anneeMois): float
    {
        if ($this->estPayeMois($anneeMois)) {
            return 0.0;
        }

        $totalDu = $this->totalCommissionMois($anneeMois);
        $paiement = $this->paiementMois($anneeMois);

        if ($paiement) {
            return max(0.0, $totalDu - (float) $paiement->montant_paye);
        }

        return $totalDu;
    }
}
